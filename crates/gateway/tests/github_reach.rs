/// The registry's own workload identity: the one principal the registry-reach surface admits.
const REGISTRY_SA: &str = "system:serviceaccount:switchboard:registry";

/// The reach-report entry, which serves the report's tool and nothing else.
const REPORT_ENTRY: &str = "github-reach-report";

/// The surface the report's tool is served on.
const REACH_SURFACE: &str = "registry-reach";

/// The drift interval the running tests use.
const INTERVAL: Duration = Duration::from_secs(1);

/// The repositories the App's installation is on at first, which the entry's reach records.
const INSTALLED: [&str; 4] = ["atlas", "borealis", "cosmos", "secret"];

/// The entry's three tools, withdrawn together on a mismatch: the derived revision's names.
const ENTRY_TOOLS: &str = "github__get_file,github__get_issue,github__get_pr";

/// The App's key, generated by the run that uses it, as PKCS#1 PEM and the public half in DER.
static KEY: LazyLock<(String, Vec<u8>)> = LazyLock::new(|| {
    let key = RsaPrivateKey::new(&mut rand_core::OsRng, 2048).unwrap();
    (
        key.to_pkcs1_pem(LineEnding::LF).unwrap().to_string(),
        key.to_public_key()
            .to_pkcs1_der()
            .unwrap()
            .as_bytes()
            .to_vec(),
    )
});

/// A directory of its own, short enough for a socket path, open to its owner only.
fn scratch() -> PathBuf {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let dir = std::env::temp_dir().join(format!(
        "sbrr-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::DirBuilder::new().mode(0o700).create(&dir).unwrap();
    dir
}

fn write(path: &Path, text: &str, mode: u32) {
    std::fs::write(path, text).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode)).unwrap();
}

/// The registry file at `revision`, every tool approved at `approved_at`: the GitHub entry
/// serving the three read tools to team A and team B, its reach the installation's repositories
/// and its reach checked against the report; and the reach-report entry serving the report's
/// tool on the registry-reach surface to the registry's own principal alone.
fn registry_text(revision: &str, approved_at: &str) -> String {
    let reach: Vec<String> = INSTALLED
        .iter()
        .map(|name| {
            format!(r#"  {{ system = "github", kind = "repository", identifier = "{ACCOUNT}/{name}" }},"#)
        })
        .collect();
    let head = |served: bool| {
        let (github, reaching) = if served {
            (
                format!(r#"["{GET_FILE}", "{GET_ISSUE}", "{GET_PR}"]"#),
                format!(r#"["{REPORT_TOOL}"]"#),
            )
        } else {
            ("[]".to_owned(), "[]".to_owned())
        };
        format!(
            r#"revision = "{revision}"
servers = []
tools = []

[[connectors]]
name = "{ENTRY}"
system = "github"
permissions = {PERMISSIONS}
tools = ["{GET_FILE}", "{GET_ISSUE}", "{GET_PR}"]
credential = {{ mode = "team_service_identity", principal = "switchboard-test-app" }}
narrowing = "limit"
permits = "read"
reach = [
{reach}
]
reach_report = {{ tool = "{REPORT_TOOL}" }}

[[connectors]]
name = "{REPORT_ENTRY}"
system = "github"
permissions = {{ metadata = "read" }}
tools = ["{REPORT_TOOL}"]
credential = {{ mode = "team_service_identity", principal = "switchboard-test-app" }}
narrowing = "none"
permits = "read"
reports_reach = true

[[surfaces]]
name = "{SURFACE}"
tools = {github}
teams = ["team-a", "team-b"]
principals = "any_in_teams_and_groups"

[[surfaces]]
name = "{REACH_SURFACE}"
tools = {reaching}
teams = ["registry"]
principals = {{ only = [{{ issuer = "{issuer}", subject = "{REGISTRY_SA}" }}] }}

[[profiles]]
name = "workload-read"
classifications = ["read"]
requires_delegation = false

[[profile_rules]]
issuer = "{issuer}"
principal = "workload"
profile = "workload-read"

[limits.teams]
team-a = [
  {{ system = "github", kind = "repository", identifier = "{ACCOUNT}/atlas" }},
  {{ system = "github", kind = "repository", identifier = "{ACCOUNT}/borealis" }},
]
team-b = [{{ system = "github", kind = "repository", identifier = "{ACCOUNT}/cosmos" }}]
registry = []
"#,
            reach = reach.join("\n"),
            issuer = files::CLUSTER_ISSUER,
        )
    };
    // The surfaces name the tools before they are approved, so the entries alone are loaded to
    // hash them.
    let entries = Registry::from_toml_str(&head(false)).unwrap();
    let binding = |entry: &str| {
        built_in_binding_sha256(&entries.connectors()[&ConnectorName::new(entry)]).unwrap()
    };
    let mut text = head(true);
    let mut approvals = Vec::new();
    // The entry's own three tools, of the connector's read tools.
    let own = connector_github::definitions()
        .into_iter()
        .filter(|definition| [GET_FILE, GET_ISSUE, GET_PR].contains(&definition.name));
    for definition in own {
        let resources = r#"{ from_arguments = [{ from_argument = "repo", qualified_by = "owner", system = "github", kind = "repository" }] }"#;
        approvals.push((definition, ENTRY, resources));
    }
    approvals.push((
        connector_github::report::definition(),
        REPORT_ENTRY,
        r#""no_resources""#,
    ));
    for (definition, entry, resources) in approvals {
        let schema = toml::Value::try_from(&definition.input_schema).unwrap();
        let mut approval = toml::Table::new();
        approval.insert("name".into(), definition.name.into());
        approval.insert("connector".into(), entry.into());
        approval.insert("classification".into(), "read".into());
        approval.insert("description".into(), definition.description.into());
        approval.insert("input_schema".into(), schema);
        approval.insert("approved_by".into(), "reviewer@example.test".into());
        approval.insert(
            "approved_at".into(),
            toml::Value::Datetime(approved_at.parse().unwrap()),
        );
        approval.insert("definition_sha256".into(), definition.sha256().into());
        approval.insert("binding_sha256".into(), binding(entry).into());
        let resources =
            toml::from_str::<toml::Table>(&format!("r = {resources}")).unwrap()["r"].clone();
        approval.insert("resources".into(), resources);
        let mut wrapper = toml::Table::new();
        wrapper.insert(
            "built_in_tools".into(),
            toml::Value::Array(vec![toml::Value::Table(approval)]),
        );
        text.push('\n');
        text.push_str(&toml::to_string(&wrapper).unwrap());
    }
    text
}

/// The first approval time.
const FIRST: &str = "2026-10-15T00:00:00Z";

/// A log writer the test reads back.
#[derive(Clone, Default)]
struct Captured(Arc<Mutex<Vec<u8>>>);

impl std::io::Write for Captured {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(bytes);
        Ok(bytes.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl Captured {
    /// Logs on this thread into a new capture until the guard is dropped. The tests run on one
    /// thread, so every task they spawn logs here too.
    fn start() -> (Self, tracing::subscriber::DefaultGuard) {
        let captured = Self::default();
        let writer = captured.clone();
        let subscriber = tracing_subscriber::fmt()
            .json()
            .with_max_level(tracing::Level::INFO)
            .with_writer(move || writer.clone())
            .finish();
        (captured, tracing::subscriber::set_default(subscriber))
    }

    /// Each line whose `event` is `event`, as its level and fields.
    fn events(&self, event: &str) -> Vec<(String, Value)> {
        let logged = String::from_utf8(self.0.lock().unwrap().clone()).unwrap();
        logged
            .lines()
            .map(|line| serde_json::from_str::<Value>(line).unwrap())
            .filter(|line| line["fields"]["event"] == event)
            .map(|line| {
                (
                    line["level"].as_str().unwrap().to_owned(),
                    line["fields"].clone(),
                )
            })
            .collect()
    }
}

/// One gateway replica with the GitHub connector, the key custodian on the fake App API, the
/// fake REST API, and a drift pass whose reach check calls this replica's own listener.
struct World {
    dir: PathBuf,
    app: Arc<FakeGitHub>,
    rest: FakeRest,
    /// The job log host the deployment pins, which no test here reads from.
    _log_host: FakeLogHost,
    custodian: Option<Running>,
    record: Buffer,
    store: Arc<InMemoryAuditStore>,
    address: SocketAddr,
    reloader: Reloader,
    drift: Option<DriftPass>,
    /// The drift pass running on its schedule, once [`World::run`] starts it.
    running: Option<tokio::task::JoinHandle<()>>,
}

impl Drop for World {
    fn drop(&mut self) {
        if let Some(running) = self.running.take() {
            running.abort();
        }
        drop(self.custodian.take());
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// The UID this test runs as, which the custodian serves.
fn my_uid() -> u32 {
    std::fs::metadata(env!("CARGO_MANIFEST_DIR")).unwrap().uid()
}

impl World {
    async fn new() -> Self {
        let dir = scratch();
        let app = Arc::new(
            FakeGitHub::start(FakeApp {
                public_key_der: KEY.1.clone(),
                app_id: APP_ID.into(),
                installation_id: INSTALLATION,
                account: ACCOUNT.into(),
                repositories: INSTALLED.into_iter().map(str::to_owned).collect(),
            })
            .await
            .unwrap(),
        );
        let rest = FakeRest::start(app.clone(), ACCOUNT).await.unwrap();
        let log_host = FakeLogHost::start().await.unwrap();
        let registry = registry_text("r1", FIRST);
        write(&dir.join("registry.toml"), &registry, 0o644);
        write(&dir.join("app-key.pem"), &KEY.0, 0o600);
        write(&dir.join("jwks.json"), &issuer().jwks_document(), 0o644);
        write(
            &dir.join("teams.toml"),
            &format!(
                "[subjects]\n\"{TEAM_A}\" = \"team-a\"\n\"{TEAM_B}\" = \"team-b\"\n\
                 \"{REGISTRY_SA}\" = \"registry\"\n"
            ),
            0o644,
        );
        write(
            &dir.join("registry-token"),
            &format!("{}\n", token(REGISTRY_SA)),
            0o600,
        );
        let socket = dir.join("c.sock");
        write(
            &dir.join("gateway.toml"),
            &deployment_text(&rest.url(), &socket, &log_host.url(), ""),
            0o644,
        );
        let record = Buffer::default();
        let config = Config {
            socket: socket.clone(),
            socket_mode: 0o600,
            peer_uid: my_uid(),
            registry: dir.join("registry.toml"),
            registry_poll_seconds: 1,
            metrics: None,
            github: GitHubSection {
                api_url: app.url(),
                ca_file: None,
                app_id: APP_ID.into(),
                installation_id: INSTALLATION,
                account: ACCOUNT.into(),
                key_file: dir.join("app-key.pem"),
                deadline_seconds: 2,
            },
            limits: Limits {
                requests_per_minute: 3600,
                burst: 1000,
                ..Limits::default()
            },
        };
        let custodian = start_custodian(config, Box::new(record.clone()))
            .await
            .unwrap();

        let deployment = Deployment::load(&dir.join("gateway.toml"), |_| None).unwrap();
        let registry = Registry::from_toml_str(&registry).unwrap();
        let store = Arc::new(InMemoryAuditStore::new());
        let wiring = start::wire_github(
            &registry,
            deployment.github.as_ref(),
            &deployment.connectors,
            Wiring::new(Arc::new(SystemClock)).audit_store(store.clone()),
        )
        .unwrap();
        let settings = Settings {
            deployment: deployment.deployment.clone(),
            identity: deployment.identity.clone(),
            audit: AuditSection {
                disabled: false,
                postgres: false,
            },
            grants: Default::default(),
            http: deployment.http.clone(),
            max_age: None,
            read_at: Instant::now(),
        };
        let (gates, reloader) = boot::check_registry(settings, registry, wiring).unwrap();
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let reach = ReachSettings::from_fields(
            Some(Path::new("registry-token")),
            Some(&format!("http://{address}/mcp/{REACH_SURFACE}")),
            Some("127.0.0.1"),
            &deployment.http.allowed_hosts,
            &dir,
        )
        .unwrap()
        .unwrap();
        let drift = DriftPass::new(
            reloader.withdrawals(),
            BTreeMap::new(),
            BTreeMap::new(),
            INTERVAL,
        )
        .with_reach(ReachCaller::new(reach), &BTreeMap::new())
        .with_report_deadlines(&deployment.connectors);
        let (telemetry, drain) = Telemetry::bounded(TELEMETRY_QUEUE);
        tokio::spawn(serve_with_telemetry(
            listener,
            gates,
            telemetry,
            drain,
            std::future::pending(),
            Timeouts::default(),
            64,
        ));
        Self {
            dir,
            app,
            rest,
            _log_host: log_host,
            custodian: Some(custodian),
            record,
            store,
            address,
            reloader,
            drift: Some(drift),
            running: None,
        }
    }

    fn drift(&self) -> &DriftPass {
        self.drift.as_ref().unwrap()
    }

    /// Runs the drift pass on its schedule, from now on.
    fn run(&mut self) {
        self.running = Some(tokio::spawn(self.drift.take().unwrap().run()));
    }

    fn withdrawn(&self, drift: &DriftPass) -> BTreeSet<String> {
        drift
            .withdrawals()
            .standing()
            .iter()
            .map(|tool| tool.as_str().to_owned())
            .collect()
    }

    /// `switchboard_reach_checks_total` of the entry for `result`, from `drift`'s counts.
    fn checks(drift: &DriftPass, result: &str) -> u64 {
        let (telemetry, _drain) = Telemetry::bounded(TELEMETRY_QUEUE);
        let text = Metrics::new(telemetry, None)
            .with_drift(drift.signals())
            .render();
        let series =
            format!("switchboard_reach_checks_total{{server=\"{ENTRY}\",result=\"{result}\"}} ");
        text.lines()
            .find_map(|line| line.strip_prefix(&series))
            .map_or(0, |value| value.parse().unwrap())
    }

    /// One `tools/call` of `tool` with `arguments` on `surface`, as `subject`.
    async fn call(&self, surface: &str, subject: &str, tool: &str, arguments: Value) -> Value {
        let body = legacy("tools/call", json!({"name": tool, "arguments": arguments}))
            .to_string()
            .into_bytes();
        let http = Http::new("POST", &format!("/mcp/{surface}"))
            .header("host", "127.0.0.1")
            .header("content-type", "application/json")
            .header("accept", "application/json, text/event-stream")
            .bearer(&token(subject))
            .header("content-length", &body.len().to_string())
            .body(body);
        let mut bytes = http.head();
        bytes.extend_from_slice(&http.body);
        let answer = tokio::time::timeout(PATIENCE, exchange(self.address, &bytes))
            .await
            .unwrap();
        answer.json()
    }

    /// Applies the registry `text`, as the reloader does when the file changes, and writes it
    /// for the custodian, which reads it again every second.
    fn reload(&self, text: &str) -> String {
        write(&self.dir.join("registry.toml"), text, 0o644);
        self.reloader
            .apply(&Registry::from_toml_str(text).unwrap())
            .unwrap()
            .as_str()
            .to_owned()
    }

    /// The report tool's rows, each as `subject surface outcome`.
    fn report_rows(&self) -> Vec<String> {
        self.store
            .rows()
            .iter()
            .filter(|row| row.tool == REPORT_TOOL)
            .map(|row| {
                let outcome = match row
                    .completion
                    .as_ref()
                    .map(|done: &Completion| &done.outcome)
                {
                    Some(Outcome::Ok) => "ok".to_owned(),
                    Some(other) => format!("{other:?}"),
                    None => "none".to_owned(),
                };
                format!(
                    "{} {} {outcome}",
                    row.proved_principal.get().id.subject.as_str(),
                    row.surface.as_str()
                )
            })
            .collect()
    }
}

/// A report that lists exactly the recorded reach holds, and withdraws nothing. Its call is a
/// gateway call by the registry's principal on registry-reach, with its own row, and its token
/// is the custodian's one exception: asked for with no repositories, so for the installation's
/// whole list, and for `metadata: read` alone.
#[tokio::test]
async fn a_matching_report_holds_with_an_installation_wide_metadata_read_token() {
    let (captured, _guard) = Captured::start();
    let world = World::new().await;
    world.drift().reach_pass().await;

    assert_eq!(World::checks(world.drift(), "held"), 1);
    assert_eq!(World::checks(world.drift(), "mismatch"), 0);
    assert_eq!(World::checks(world.drift(), "failed"), 0);
    assert!(world.withdrawn(world.drift()).is_empty());
    let held = captured.events("reach_held");
    assert_eq!(held.len(), 1, "{held:?}");
    assert_eq!(held[0].0, "INFO");
    assert_eq!(held[0].1["check"], "vendor_report");
    assert_eq!(held[0].1["server"], ENTRY);
    assert_eq!(held[0].1["tool"], REPORT_TOOL);

    let issued = world.app.issued();
    assert_eq!(issued.len(), 1, "{issued:?}");
    assert_eq!(
        issued[0].asked_repositories, None,
        "the report's token is asked for the installation's whole list"
    );
    assert_eq!(
        issued[0].asked_permissions,
        Some(BTreeMap::from([("metadata".to_owned(), "read".to_owned())])),
        "and for metadata: read alone"
    );
    let requested: Vec<String> = world
        .rest
        .requests()
        .iter()
        .map(|request| format!("{} {}?{}", request.method, request.path, request.query))
        .collect();
    assert_eq!(
        requested,
        ["GET /installation/repositories?per_page=100&page=1"]
    );
    world.settle().await;
    assert_eq!(
        world.report_rows(),
        [format!("{REGISTRY_SA} {REACH_SURFACE} ok")]
    );
    let line = world.record.text();
    assert!(line.contains("\"team\":\"registry\""), "{line}");
    assert!(line.contains("\"repository_count\":0"), "{line}");

    // The report's tool is served to the registry's principal alone: a team's workload is not
    // admitted to the surface, and the team's own surface does not serve the tool.
    for surface in [REACH_SURFACE, SURFACE] {
        let answer = world.call(surface, TEAM_A, REPORT_TOOL, json!({})).await;
        assert!(answer.get("error").is_some(), "{surface}: {answer}");
    }
    assert_eq!(world.app.issued().len(), 1, "no token for a refused call");
}

impl World {
    /// Waits a moment for a row's completion to be written after its answer.
    async fn settle(&self) {
        tokio::time::sleep(Duration::from_millis(20)).await;
    }
}

/// A repository added to the installation, or dropped from it, without a new approval is a
/// mismatch: every tool of the entry is withdrawn, with its own cause, within the interval of
/// the change, while the report's own tool, another entry's, stays served.
#[tokio::test]
async fn an_added_or_dropped_repository_withdraws_the_entrys_tools_within_the_interval() {
    for (change, added, dropped) in [
        ("added", "example-org/newcomer", ""),
        ("dropped", "", "example-org/secret"),
    ] {
        let (captured, _guard) = Captured::start();
        let mut world = World::new().await;
        let signals = world.drift().signals();
        let withdrawals = world.drift().withdrawals().clone();
        world.run();
        // The first check runs at once.
        eventually("the first check holds", || {
            signals
                .counts()
                .iter()
                .any(|(server, counts)| server.as_str() == ENTRY && counts.reach_held >= 1)
        })
        .await;
        assert!(withdrawals.standing().is_empty());
        let answer = world
            .call(
                SURFACE,
                TEAM_A,
                GET_FILE,
                json!({"owner": ACCOUNT, "repo": "atlas", "path": "x"}),
            )
            .await;
        assert!(answer.get("error").is_none(), "{answer}");

        if change == "added" {
            world.rest.add_repository("newcomer");
        } else {
            world.rest.drop_repository("secret");
        }
        let changed = tokio::time::Instant::now();
        eventually("the entry's tools are withdrawn", || {
            !withdrawals.standing().is_empty()
        })
        .await;
        // The next tick comes within the interval, and its check within the report tool's call
        // deadline plus the allowance; here it takes milliseconds.
        assert!(
            changed.elapsed() <= INTERVAL + REACH_ALLOWANCE,
            "{change}: withdrawn {:?} after the change",
            changed.elapsed()
        );
        let withdrawn: BTreeSet<String> = withdrawals
            .standing()
            .iter()
            .map(|tool| tool.as_str().to_owned())
            .collect();
        assert_eq!(
            withdrawn,
            BTreeSet::from([GET_FILE.to_owned(), GET_ISSUE.to_owned(), GET_PR.to_owned()]),
            "{change}"
        );

        let mismatch = captured.events("reach_mismatch");
        assert_eq!(mismatch.len(), 1, "{change}: {mismatch:?}");
        assert_eq!(mismatch[0].0, "ERROR");
        assert_eq!(mismatch[0].1["check"], "vendor_report");
        assert_eq!(mismatch[0].1["added"], added, "{change}");
        assert_eq!(mismatch[0].1["dropped"], dropped, "{change}");
        assert_eq!(mismatch[0].1["withdrawn"], 3);
        let causes: Vec<(String, String)> = captured
            .events("tool_withdrawn")
            .into_iter()
            .map(|(level, fields)| {
                assert_eq!(fields["server"], ENTRY);
                (level, fields["cause"].as_str().unwrap().to_owned())
            })
            .collect();
        assert_eq!(
            causes,
            vec![("ERROR".to_owned(), "reach report mismatch".to_owned()); 3],
            "{change}"
        );
        assert_eq!(
            captured.events("tool_withdrawn")[0].1["revision"],
            format!("r1+withdrawn:{ENTRY_TOOLS}")
        );

        // Withdrawn from every surface: team A's call is refused, and the report's tool, on the
        // reach-report entry, is still served to the registry.
        let answer = world
            .call(
                SURFACE,
                TEAM_A,
                GET_FILE,
                json!({"owner": ACCOUNT, "repo": "atlas", "path": "x"}),
            )
            .await;
        assert!(answer.get("error").is_some(), "{change}: {answer}");
        let answer = world
            .call(REACH_SURFACE, REGISTRY_SA, REPORT_TOOL, json!({}))
            .await;
        assert_eq!(
            answer["result"]["isError"],
            json!(false),
            "{change}: {answer}"
        );
    }
}

/// A report that cannot be read, here GitHub answering 500, is logged and counted as failed and
/// withdraws nothing, as a failed canary does; the next tick tries again, and once GitHub
/// answers, the report holds.
#[tokio::test]
async fn a_failed_report_is_logged_and_retried_and_withdraws_nothing() {
    let (captured, _guard) = Captured::start();
    let mut world = World::new().await;
    let signals = world.drift().signals();
    let withdrawals = world.drift().withdrawals().clone();
    world.rest.set_mode(Mode::Status(500));
    world.run();
    let count = |result: fn(&gateway::DriftCounts) -> u64| {
        signals
            .counts()
            .iter()
            .filter(|(server, _)| server.as_str() == ENTRY)
            .map(|(_, counts)| result(counts))
            .sum::<u64>()
    };
    eventually("two failed checks, the second on the next tick", || {
        count(|counts| counts.reach_failed) >= 2
    })
    .await;
    assert!(withdrawals.standing().is_empty());
    assert_eq!(count(|counts| counts.reach_mismatch), 0);
    let failed = captured.events("reach_check_failed");
    assert!(failed.len() >= 2, "{failed:?}");
    assert_eq!(failed[0].0, "WARN");
    assert_eq!(failed[0].1["check"], "vendor_report");
    assert_eq!(failed[0].1["server"], ENTRY);
    assert!(
        failed[0].1["reason"].as_str().unwrap().contains("HTTP 500"),
        "{failed:?}"
    );
    assert!(captured.events("tool_withdrawn").is_empty());

    world.rest.set_mode(Mode::Normal);
    eventually("a check holds once GitHub answers", || {
        count(|counts| counts.reach_held) >= 1
    })
    .await;
    assert!(withdrawals.standing().is_empty());
}

/// A withdrawal stands until a new approval: a report that matches again does not clear it, and
/// approving the entry's tools again does. A report that still differs after the new approval
/// would withdraw them again; here the installation is back as recorded, and the next report
/// holds.
#[tokio::test]
async fn a_new_approval_clears_a_withdrawal_and_a_matching_report_does_not() {
    let world = World::new().await;
    world.rest.drop_repository("secret");
    world.drift().reach_pass().await;
    assert_eq!(world.withdrawn(world.drift()).len(), 3);

    world.rest.add_repository("secret");
    world.drift().reach_pass().await;
    assert_eq!(World::checks(world.drift(), "held"), 1);
    assert_eq!(
        world.withdrawn(world.drift()).len(),
        3,
        "a report that matches again does not serve the tools"
    );

    let revision = world.reload(&registry_text("r2", "2026-10-16T00:00:00Z"));
    assert_eq!(revision, "r2", "the new approval clears every withdrawal");
    assert!(world.withdrawn(world.drift()).is_empty());
    let answer = world
        .call(
            SURFACE,
            TEAM_A,
            GET_FILE,
            json!({"owner": ACCOUNT, "repo": "atlas", "path": "x"}),
        )
        .await;
    assert!(answer.get("error").is_none(), "{answer}");

    // The custodian reads the new revision within a second; until then a report is a stale
    // request, which fails and withdraws nothing.
    let deadline = tokio::time::Instant::now() + PATIENCE;
    while World::checks(world.drift(), "held") < 2 {
        assert!(tokio::time::Instant::now() < deadline, "no report held");
        world.drift().reach_pass().await;
        assert!(world.withdrawn(world.drift()).is_empty());
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
}

/// Start refuses a registry with a reach report when the deployment file gives no `[drift]
/// reach_*` settings, naming the entry, as it does an entry with a canary: its reach would never
/// be checked.
#[tokio::test]
async fn start_refuses_a_reach_report_with_no_reach_settings() {
    let world = World::new().await;
    let deployment = Deployment::load(&world.dir.join("gateway.toml"), |_| None).unwrap();
    let refused = start::prepare(
        deployment,
        InstanceName::new("reach-report-test"),
        Arc::new(SystemClock),
    )
    .await
    .unwrap_err();
    assert!(
        matches!(
            &refused,
            start::StartError::NoReachSettings(entries)
                if entries == &[ConnectorName::new(ENTRY)]
        ),
        "{refused:?}"
    );
    assert!(refused.to_string().contains("a reach report"), "{refused}");
}
