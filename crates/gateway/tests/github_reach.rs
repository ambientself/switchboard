//! The reach check's vendor-report kind, for GitHub (decision 0011, section 4; #193), end to
//! end: a GitHub entry whose recorded reach is checked against GitHub's own report of the App
//! installation's repositories, read by a reach-report entry's tool through the gateway's own
//! listener, as the registry's workload, on its `registry-reach` surface. The key custodian runs
//! on its fake GitHub App API, the fake GitHub REST API reports the installation's
//! repositories, and the drift pass is driven by the test or run on its schedule.
//!
//! A matching report holds, with an installation-wide `metadata: read` token; a repository added
//! to the installation, or dropped from it, withdraws the entry's tools within the interval; a
//! report that cannot be read is logged, tried again and withdraws nothing; a new approval
//! clears a withdrawal, and nothing else does; and the start is refused with a reach report and
//! no reach settings.
