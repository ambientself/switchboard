//! A custodian on a fake GitHub, with a key generated per run and a registry written per test.
#![allow(clippy::unwrap_used, clippy::expect_used, dead_code)]

use std::collections::{BTreeMap, BTreeSet};
use std::io::Write;
use std::os::unix::fs::{DirBuilderExt, MetadataExt, PermissionsExt};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, LazyLock, Mutex};
use std::time::Duration;

use gateway_core::{PolicyRevision, TeamId, ToolName};
use gateway_registry::Access;
use key_custodian::fake::{FakeApp, FakeGitHub};
use key_custodian::start::{Config, GitHubSection, Limits};
use key_custodian::{CustodianClient, Running, StartError, TokenRequest, start};
use rsa::RsaPrivateKey;
use rsa::pkcs1::{EncodeRsaPrivateKey, EncodeRsaPublicKey, LineEnding};

pub const ACCOUNT: &str = "example-org";
pub const APP_ID: &str = "4242";
pub const INSTALLATION: u64 = 7;

/// An App key, generated by the run that uses it.
pub struct TestKey {
    /// The private key in PKCS#1 PEM, as GitHub issues one.
    pub private_pem: String,
    /// The public key in PKCS#1 DER, for the fake.
    pub public_der: Vec<u8>,
}

fn generate() -> TestKey {
    let key = RsaPrivateKey::new(&mut rand_core::OsRng, 2048).unwrap();
    TestKey {
        private_pem: key.to_pkcs1_pem(LineEnding::LF).unwrap().to_string(),
        public_der: key
            .to_public_key()
            .to_pkcs1_der()
            .unwrap()
            .as_bytes()
            .to_vec(),
    }
}

/// The App's key.
pub static KEY: LazyLock<TestKey> = LazyLock::new(generate);
/// Another key, which the fake does not know.
pub static OTHER_KEY: LazyLock<TestKey> = LazyLock::new(generate);

/// The UID this test runs as.
pub fn my_uid() -> u32 {
    std::fs::metadata(env!("CARGO_MANIFEST_DIR")).unwrap().uid()
}

/// A directory of its own, short enough for a socket path, open to its owner only.
pub fn scratch() -> PathBuf {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let dir = std::env::temp_dir().join(format!(
        "kc-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::DirBuilder::new().mode(0o700).create(&dir).unwrap();
    dir
}

/// Writes `text` to `path` with `mode`.
pub fn write_file(path: &Path, text: &str, mode: u32) {
    std::fs::write(path, text).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode)).unwrap();
}

/// `count` repositories of the big team: `example-org/r0` and on.
pub fn big_repositories(count: usize) -> Vec<String> {
    (0..count).map(|n| format!("{ACCOUNT}/r{n}")).collect()
}

/// The registry file at `revision`: two GitHub entries, a read entry and a propose entry, and
/// three teams. `team-a` has atlas and borealis, `team-b` has cosmos, and `big` has 501
/// repositories. Atlas is also limited to `team-a` under the docs system, which the custodian
/// ignores.
pub fn registry(revision: &str) -> String {
    let big: Vec<String> = big_repositories(501)
        .iter()
        .map(|name| {
            format!(r#"{{ system = "github", kind = "repository", identifier = "{name}" }}"#)
        })
        .collect();
    format!(
        r#"revision = "{revision}"
servers = []
tools = []
surfaces = []
profiles = []
profile_rules = []

[[connectors]]
name = "github-read"
system = "github"
permissions = {{ contents = "read", issues = "read", pull_requests = "read" }}
tools = ["github__get_issue", "github__get_file"]

[[connectors]]
name = "github-propose"
system = "github"
permissions = {{ contents = "write", pull_requests = "write" }}
tools = ["github__propose"]

[[connectors]]
name = "jira-read"
system = "jira"
permissions = {{ issues = "write" }}
tools = ["jira__get_issue"]

[limits.teams]
team-a = [
  {{ system = "github", kind = "repository", identifier = "{ACCOUNT}/atlas" }},
  {{ system = "github", kind = "repository", identifier = "{ACCOUNT}/borealis" }},
  {{ system = "github", kind = "repository", identifier = "other-org/elsewhere" }},
  {{ system = "docs", kind = "project", identifier = "{ACCOUNT}/hidden" }},
]
team-b = [{{ system = "github", kind = "repository", identifier = "{ACCOUNT}/cosmos" }}]
big = [{}]
"#,
        big.join(", ")
    )
}

/// A buffer the record is written to.
#[derive(Clone, Default)]
pub struct Buffer(Arc<Mutex<Vec<u8>>>);

impl Write for Buffer {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(bytes);
        Ok(bytes.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl Buffer {
    pub fn text(&self) -> String {
        String::from_utf8(self.0.lock().unwrap().clone()).unwrap()
    }

    pub fn lines(&self) -> Vec<serde_json::Value> {
        self.text()
            .lines()
            .map(|line| serde_json::from_str(line).unwrap())
            .collect()
    }
}

/// A custodian, its fake GitHub, and a client.
pub struct World {
    pub dir: PathBuf,
    pub fake: FakeGitHub,
    pub running: Option<Running>,
    pub client: CustodianClient,
    pub record: Buffer,
    pub registry: PathBuf,
}

impl Drop for World {
    fn drop(&mut self) {
        drop(self.running.take());
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// The fake's App: the installation on `example-org`, with every repository the registry
/// names there and one more, `secret`, that no team's limit holds.
pub fn fake_app() -> FakeApp {
    let mut repositories: BTreeSet<String> = ["atlas", "borealis", "cosmos", "secret"]
        .into_iter()
        .map(str::to_owned)
        .collect();
    repositories.extend((0..501).map(|n| format!("r{n}")));
    FakeApp {
        public_key_der: KEY.public_der.clone(),
        app_id: APP_ID.into(),
        installation_id: INSTALLATION,
        account: ACCOUNT.into(),
        repositories,
    }
}

/// The configuration for a custodian in `dir`, on `fake`.
pub fn config(dir: &Path, fake: &FakeGitHub) -> Config {
    Config {
        socket: dir.join("c.sock"),
        socket_mode: 0o600,
        peer_uid: my_uid(),
        registry: dir.join("registry.toml"),
        registry_poll_seconds: 1,
        metrics: Some("127.0.0.1:0".parse().unwrap()),
        github: GitHubSection {
            api_url: fake.url(),
            ca_file: None,
            app_id: APP_ID.into(),
            installation_id: INSTALLATION,
            account: ACCOUNT.into(),
            key_file: dir.join("app-key.pem"),
            deadline_seconds: 2,
        },
        limits: Limits::default(),
    }
}

/// Writes the key and the registry at `r1` into `dir`.
pub fn files(dir: &Path, key: &TestKey) {
    write_file(&dir.join("app-key.pem"), &key.private_pem, 0o600);
    write_file(&dir.join("registry.toml"), &registry("r1"), 0o644);
}

impl World {
    /// A custodian with the defaults.
    pub async fn new() -> Self {
        Self::with(|_| {}).await
    }

    /// A custodian whose configuration `adjust` changes first.
    pub async fn with(adjust: impl FnOnce(&mut Config)) -> Self {
        Self::try_with(adjust).await.unwrap()
    }

    /// A custodian whose configuration `adjust` changes first, or why it did not start.
    #[allow(clippy::result_large_err)]
    pub async fn try_with(adjust: impl FnOnce(&mut Config)) -> Result<Self, (StartError, PathBuf)> {
        let dir = scratch();
        files(&dir, &KEY);
        let fake = FakeGitHub::start(fake_app()).await.unwrap();
        let mut config = config(&dir, &fake);
        adjust(&mut config);
        let record = Buffer::default();
        let registry = config.registry.clone();
        let socket = config.socket.clone();
        match start(config, Box::new(record.clone())).await {
            Ok(running) => Ok(Self {
                dir,
                fake,
                running: Some(running),
                client: CustodianClient::new(socket, Duration::from_secs(5)),
                record,
                registry,
            }),
            Err(error) => {
                let _ = std::fs::remove_dir_all(&dir);
                Err((error, socket))
            }
        }
    }

    pub fn running(&self) -> &Running {
        self.running.as_ref().unwrap()
    }

    /// `GET /metrics` on the custodian's metrics listener, by hand.
    pub async fn metrics(&self) -> String {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let address = self.running().metrics().unwrap();
        let mut stream = tokio::net::TcpStream::connect(address).await.unwrap();
        stream
            .write_all(b"GET /metrics HTTP/1.1\r\nHost: metrics\r\nConnection: close\r\n\r\n")
            .await
            .unwrap();
        let mut answer = String::new();
        stream.read_to_string(&mut answer).await.unwrap();
        answer
    }

    /// Sends `line` as it is and returns every byte of the answer.
    pub async fn raw(&self, line: &[u8]) -> Vec<u8> {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let mut stream = tokio::net::UnixStream::connect(self.running().socket())
            .await
            .unwrap();
        stream.write_all(line).await.unwrap();
        let mut answer = Vec::new();
        stream.read_to_end(&mut answer).await.unwrap();
        answer
    }
}

/// A request from `team-a` for `github__get_issue` on atlas with `issues: read`, at `r1`.
pub fn request() -> TokenRequest {
    TokenRequest {
        team: TeamId::new("team-a"),
        tool: ToolName::parse("github__get_issue").unwrap(),
        repositories: vec![format!("{ACCOUNT}/atlas")],
        permissions: BTreeMap::from([("issues".to_owned(), Access::Read)]),
        revision: PolicyRevision::new("r1"),
    }
}
